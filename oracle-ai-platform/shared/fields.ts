export const FIELDS: Record<string, string[]> = Object.fromEntries(
  Object.entries(DICTIONARY).map(([k, v]) => [k, v.map((x) => x.name)]),
);
export const fieldType = (entity: string, name: string): FieldType | null =>
  DICTIONARY[entity]?.find((x) => x.name === name)?.type ?? null;
export const template = (type: string) =>
  (FIELDS[type] || ["id"]).join(",") + "\n";
