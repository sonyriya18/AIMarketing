import { randomUUID } from 'node:crypto';
import { describe, expect, it } from 'vitest';
import { BlobStorage, type BlobStoreLike } from '../../server/integrations/storage/storage';

/** In-memory stand-in for a Netlify Blobs store (test boundary only). */
function memoryStore(): BlobStoreLike & { keys: () => string[] } {
  const m = new Map<string, ArrayBuffer>();
  return {
    keys: () => [...m.keys()],
    set: async (k, d) => void m.set(k, d.slice(0)),
    get: async (k) => m.get(k)?.slice(0) ?? null,
    delete: async (k) => void m.delete(k),
  };
}

describe('BlobStorage', () => {
  it('stores, reads back exactly, and removes objects under generated keys', async () => {
    const store = memoryStore();
    const s = new BlobStorage(store);
    const ws = randomUUID();
    const obj = await s.put(ws, 'import_raw', Buffer.from('a,b\n1,2\n'));
    expect(obj.key.startsWith(`${ws}/import_raw/`)).toBe(true);
    expect(obj.byteSize).toBe(8);
    expect((await s.get(obj.key)).toString()).toBe('a,b\n1,2\n');
    await s.remove(obj.key);
    await expect(s.get(obj.key)).rejects.toThrow('not found');
    expect(await s.healthy()).toBe(true);
  });

  it('rejects keys that were not generated by the server', async () => {
    const s = new BlobStorage(memoryStore());
    await expect(s.get('../etc/passwd')).rejects.toThrow('Invalid storage key');
    await expect(s.get(`${randomUUID()}/x/../../y`)).rejects.toThrow('Invalid storage key');
  });
});
