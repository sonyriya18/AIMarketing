/**
 * Local development setup (cross-platform; runs with `npm run setup:local`).
 *
 * - Creates the owner role (rci_owner: migrations) and runtime role (rci_app: NOBYPASSRLS, not an
 *   owner) plus `rci_dev` and `rci_test` databases, using PG_ADMIN_URL (a local superuser URL).
 * - Writes `.env.local` with generated local-only secrets ONLY if it does not exist.
 * - Applies migrations to both databases. Never drops or overwrites data; never enables sends.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import pg from 'pg';
import dotenv from 'dotenv';
import { migrate } from '../server/db/migrate';
import { ask, DEFAULT_AI_MODEL } from './prompt';

const ENV_FILE = '.env.local';
let adminUrl = process.env.PG_ADMIN_URL || 'postgres://postgres:postgres@localhost:5432/postgres';
const secret = (n = 24) => randomBytes(n).toString('base64url');

function existingEnv(): Record<string, string> {
  return existsSync(ENV_FILE) ? dotenv.parse(readFileSync(ENV_FILE)) : {};
}

function passwordFrom(url: string | undefined): string | null {
  if (!url) return null;
  try {
    return decodeURIComponent(new URL(url).password) || null;
  } catch {
    return null;
  }
}

async function main() {
  const env = existingEnv();
  const ownerPw = passwordFrom(env.DATABASE_MIGRATION_URL) ?? secret();
  const appPw = passwordFrom(env.DATABASE_URL) ?? secret();
  let admin = new pg.Client({ connectionString: adminUrl });
  for (let attempt = 0; ; attempt++) {
    try {
      await admin.connect();
      break;
    } catch (e) {
      const msg = (e as Error).message;
      if (/ECONNREFUSED|ENOTFOUND/.test(msg)) {
        console.error('PostgreSQL is not running on localhost:5432. Start it (Windows: Services → "postgresql-x64-16" → Start) and run this again.');
        process.exit(1);
      }
      if (!process.stdin.isTTY || process.env.PG_ADMIN_URL || attempt >= 3) {
        console.error(`Could not connect to PostgreSQL as an administrator (${msg}).`);
        console.error('Set PG_ADMIN_URL to a local superuser URL, e.g. postgres://postgres:<password>@localhost:5432/postgres');
        process.exit(1);
      }
      // Ask for the password chosen when PostgreSQL was installed (user "postgres").
      const pw = await ask('PostgreSQL password for user "postgres" (the one set when installing PostgreSQL): ', { secret: true });
      adminUrl = `postgres://postgres:${encodeURIComponent(pw)}@localhost:5432/postgres`;
      admin = new pg.Client({ connectionString: adminUrl });
    }
  }
  const host = new URL(adminUrl);
  const roleSql = async (name: string, pw: string, extra: string) => {
    const exists = await admin.query('SELECT 1 FROM pg_roles WHERE rolname = $1', [name]);
    const verb = exists.rowCount ? 'ALTER' : 'CREATE';
    await admin.query(`${verb} ROLE ${name} WITH LOGIN ${extra} PASSWORD '${pw.replace(/'/g, "''")}'`);
    console.log(`${verb === 'CREATE' ? 'created' : 'updated'} role ${name}`);
  };
  await roleSql('rci_owner', ownerPw, 'NOSUPERUSER NOCREATEROLE NOCREATEDB NOBYPASSRLS');
  await roleSql('rci_app', appPw, 'NOSUPERUSER NOCREATEROLE NOCREATEDB NOBYPASSRLS');
  for (const db of ['rci_dev', 'rci_test']) {
    const exists = await admin.query('SELECT 1 FROM pg_database WHERE datname = $1', [db]);
    if (!exists.rowCount) {
      await admin.query(`CREATE DATABASE ${db} OWNER rci_owner`);
      console.log(`created database ${db}`);
    }
    await admin.query(`GRANT CONNECT ON DATABASE ${db} TO rci_app`);
  }
  await admin.end();

  const url = (user: string, pw: string, db: string) => `postgres://${user}:${encodeURIComponent(pw)}@${host.hostname}:${host.port || 5432}/${db}`;
  if (!existsSync(ENV_FILE)) {
    const content = `# Generated by npm run setup:local — local development only. Do not commit.
NODE_ENV=development
APP_DATA_MODE=development
PORT=3000
APP_BASE_URL=http://localhost:3000
DATABASE_URL=${url('rci_app', appPw, 'rci_dev')}
DATABASE_MIGRATION_URL=${url('rci_owner', ownerPw, 'rci_dev')}
TEST_DATABASE_URL=${url('rci_app', appPw, 'rci_test')}
TEST_DATABASE_MIGRATION_URL=${url('rci_owner', ownerPw, 'rci_test')}
SESSION_SECRET=${secret(32)}
# Local identity harness (refused in production). Use AUTH_MODE=oidc with OIDC_* for real sign-in.
AUTH_MODE=dev
ALLOW_WORKSPACE_CREATION=true
STORAGE_DRIVER=filesystem
STORAGE_ROOT=./var/objects
UPLOAD_MAX_BYTES=10485760
RUN_WORKER_IN_PROCESS=true
AI_PROVIDER=none
AI_MODEL=
GEMINI_API_KEY=
ENABLE_PROVIDER_DRAFT_WRITES=false
ENABLE_PROOF_SENDS=false
ENABLE_LIVE_CAMPAIGN_SENDS=false
LOG_LEVEL=info
`;
    let finalContent = content;
    if (process.stdin.isTTY) {
      const key = await ask('Gemini API key for the AI features (press Enter to skip; you can add it later with npm run ai:key): ', { secret: true });
      if (key) {
        finalContent = finalContent
          .replace(/^AI_PROVIDER=.*$/m, 'AI_PROVIDER=gemini')
          .replace(/^AI_MODEL=.*$/m, `AI_MODEL=${DEFAULT_AI_MODEL}`)
          .replace(/^GEMINI_API_KEY=.*$/m, `GEMINI_API_KEY=${key}`);
      }
    }
    writeFileSync(ENV_FILE, finalContent, { mode: 0o600 });
    console.log(`wrote ${ENV_FILE}`);
  } else {
    console.log(`${ENV_FILE} exists; left unchanged`);
  }
  await migrate(url('rci_owner', ownerPw, 'rci_dev'));
  await migrate(url('rci_owner', ownerPw, 'rci_test'));
  console.log('\nLocal setup complete. Start the app with:  npm run dev   then open http://localhost:3000');
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
